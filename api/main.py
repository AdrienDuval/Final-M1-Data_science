# ── Simulate TV sweep ─────────────────────────────────────────────────────────

@app.get("/simulate/tv-sweep")
def tv_sweep(
    radio:      float = Query(20.0, ge=0),
    sm:         float = Query(5.0,  ge=0),
    influencer: str   = Query("Mega"),
    steps:      int   = Query(60,   ge=10, le=200),
):
    if influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    model_name = _best_reg_model()
    pipeline   = state["models"][model_name]
    tv_values  = np.linspace(0, 300, steps)

    results = []
    for tv in tv_values:
        X    = pd.DataFrame([{"TV": float(tv), "Radio": radio,
                               "Social Media": sm, "Influencer": influencer}])
        pred = float(pipeline.predict(X)[0])
        results.append({"tv": round(float(tv), 1), "sales": round(pred, 2)})

    return {
        "data":          results,
        "model":         model_name,
        "training_max_tv": 297.0,
        "current_radio": radio,
        "current_sm":    sm,
        "influencer":    influencer,
    }


# ── Prediction ────────────────────────────────────────────────────────────────

class PredictRequest(BaseModel):
    TV:           float = Field(..., ge=0, le=500)
    Radio:        float = Field(..., ge=0, le=200)
    Social_Media: float = Field(..., ge=0, le=50)
    Influencer:   str   = Field(...)

    model_config = {
        "json_schema_extra": {
            "example": {"TV": 50, "Radio": 20, "Social_Media": 5, "Influencer": "Mega"}
        }
    }


@app.post("/predict")
def predict(req: PredictRequest):
    if req.Influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    model_name   = _best_reg_model()
    pred         = float(state["models"][model_name].predict(_build_input(req))[0])
    total_budget = req.TV + req.Radio + req.Social_Media
    avg_sales    = float(state["df"][TARGET_REG].mean())

    return {
        "predicted_sales": round(pred, 2),
        "roi":             round(pred / total_budget, 4) if total_budget > 0 else 0.0,
        "total_budget":    round(total_budget, 2),
        "vs_average":      round(pred - avg_sales, 2),
        "model_used":      model_name,
    }


@app.post("/predict/all")
def predict_all(req: PredictRequest):
    if req.Influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    X_in  = _build_input(req)
    total = req.TV + req.Radio + req.Social_Media
    return {
        "predictions": [
            {
                "model":           name,
                "label":           name.replace("_", " ").title(),
                "predicted_sales": round(float(pipeline.predict(X_in)[0]), 2),
                "roi":             round(float(pipeline.predict(X_in)[0]) / total, 4)
                                   if total > 0 else 0.0,
            }
            for name, pipeline in state["models"].items()
        ]
    }


# ── Classification ────────────────────────────────────────────────────────────

@app.post("/classify")
def classify(req: PredictRequest):
    if req.Influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    clf_models = state.get("clf_models", {})
    clf_pre    = state.get("clf_preprocessor")
    clf_le     = state.get("clf_label_encoder")

    if clf_models and clf_pre and clf_le:
        # Use the best available classification model
        model = (clf_models.get("random_forest")
                 or clf_models.get("gradient_boosting")
                 or next(iter(clf_models.values())))
        X  = _build_input(req)
        Xt = clf_pre.transform(X)
        pred  = model.predict(Xt)[0]
        proba = float(model.predict_proba(Xt)[0].max())
        label = clf_le.inverse_transform([pred])[0]
    else:
        # Fallback: classify by sales quantile thresholds
        model_name = _best_reg_model()
        sales = float(state["models"][model_name].predict(_build_input(req))[0])
        if sales >= state["sales_q66"]:
            label, proba = "High",   0.80
        elif sales >= state["sales_q33"]:
            label, proba = "Medium", 0.65
        else:
            label, proba = "Low",    0.75

    return {"label": label, "confidence": round(proba, 4)}


# ── Inverse prediction (optimize budget → target sales) ───────────────────────

class OptimizeRequest(BaseModel):
    target_sales: float = Field(..., gt=0)
    max_budget:   float = Field(400.0, gt=0)
    influencer:   str   = Field("Macro")


@app.post("/optimize")
def optimize(req: OptimizeRequest):
    from scipy.optimize import minimize

    if req.influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    model_name = _best_reg_model()
    pipeline   = state["models"][model_name]
    inf        = req.influencer

    def objective(x):
        tv, radio, sm = float(x[0]), float(x[1]), float(x[2])
        X    = pd.DataFrame([{"TV": tv, "Radio": radio, "Social Media": sm, "Influencer": inf}])
        pred = float(pipeline.predict(X)[0])
        return (pred - req.target_sales) ** 2

    df = state["df"]
    x0      = [df["TV"].median(), df["Radio"].median(), df["Social Media"].median()]
    bounds  = [(0, 500), (0, 200), (0, 50)]
    cons    = [{"type": "ineq", "fun": lambda x: req.max_budget - float(x[0]+x[1]+x[2])}]

    result  = minimize(objective, x0, method="SLSQP",
                       bounds=bounds, constraints=cons,
                       options={"maxiter": 500, "ftol": 1e-8})

    opt_tv, opt_radio, opt_sm = [round(float(v), 2) for v in result.x]
    X_opt   = pd.DataFrame([{"TV": opt_tv, "Radio": opt_radio,
                              "Social Media": opt_sm, "Influencer": inf}])
    opt_pred  = round(float(pipeline.predict(X_opt)[0]), 2)
    opt_total = round(opt_tv + opt_radio + opt_sm, 2)
    opt_roi   = round((opt_pred - opt_total) / opt_total * 100, 2) if opt_total > 0 else 0.0

    return {
        "TV":             opt_tv,
        "Radio":          opt_radio,
        "Social_Media":   opt_sm,
        "total_budget":   opt_total,
        "projected_sales": opt_pred,
        "roi":            opt_roi,
        "gap":            round(opt_pred - req.target_sales, 2),
        "model_used":     model_name,
        "converged":      bool(result.success),
    }


# ── RF uncertainty / probability analysis ────────────────────────────────────

class ProbabilityRequest(BaseModel):
    TV:           float = Field(..., ge=0)
    Radio:        float = Field(..., ge=0)
    Social_Media: float = Field(..., ge=0)
    Influencer:   str   = Field(...)
    goal:         float = Field(..., gt=0)


@app.post("/probability")
def probability(req: ProbabilityRequest):
    if req.Influencer not in ("Mega", "Macro", "Micro", "Nano"):
        raise HTTPException(status_code=422, detail="Invalid Influencer value")

    rf = state["models"].get("random_forest")
    if rf is None or not hasattr(rf.named_steps.get("model", object()), "estimators_"):
        raise HTTPException(status_code=503, detail="Random Forest model not available")

    X          = _build_input(PredictRequest(
        TV=req.TV, Radio=req.Radio, Social_Media=req.Social_Media, Influencer=req.Influencer
    ))
    rf_model   = rf.named_steps["model"]
    preprocessor = rf.named_steps["preprocessor"]
    Xt         = preprocessor.transform(X)

    tree_preds = np.array([tree.predict(Xt)[0] for tree in rf_model.estimators_])
    mean_pred  = float(np.mean(tree_preds))
    std_pred   = float(np.std(tree_preds))
    prob_hit   = float(np.mean(tree_preds >= req.goal))

    # Build histogram buckets for the frontend (40 bins)
    counts, edges = np.histogram(tree_preds, bins=40)
    histogram = [
        {
            "range":    round(float(edges[i]), 1),
            "count":    int(counts[i]),
            "above_goal": bool(edges[i] >= req.goal),
        }
        for i in range(len(counts))
    ]

    return {
        "mean":            round(mean_pred, 2),
        "std":             round(std_pred, 2),
        "min":             round(float(tree_preds.min()), 2),
        "max":             round(float(tree_preds.max()), 2),
        "probability_goal": round(prob_hit, 4),
        "n_trees":         len(tree_preds),
        "histogram":       histogram,
        "goal":            req.goal,
    }

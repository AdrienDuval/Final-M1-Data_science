# ── App state (loaded once at startup) ───────────────────────────────────────
state: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    # ── Regression models (full sklearn Pipelines) ────────────────────────────
    with open(ROOT / "models" / "model_list.json") as f:
        model_names = json.load(f)
    state["models"] = {
        n: joblib.load(ROOT / "models" / f"{n}.pkl") for n in model_names
    }

    # Train/test split (saved by src/train.py)
    with open(ROOT / "models" / "splits.pkl", "rb") as f:
        state["splits"] = pickle.load(f)

    # Cross-validation results
    with open(ROOT / "models" / "cv_results.json") as f:
        state["cv"] = json.load(f)

    # Full dataset for /stats
    df = load_data()
    df["Total_Budget"] = df[NUMERIC_FEATURES].sum(axis=1)
    df["ROI"]          = df[TARGET_REG] / df["Total_Budget"]
    state["df"] = df

    # Sales quantiles for performance classification fallback
    q33, q66 = df[TARGET_REG].quantile([1 / 3, 2 / 3])
    state["sales_q33"] = float(q33)
    state["sales_q66"] = float(q66)

    # ── Classification models (separate preprocessor + estimators) ───────────
    _clf_pipe = ROOT / "models" / "pipeline_classification.pkl"
    _clf_le   = ROOT / "models" / "label_encoder.pkl"
    if _clf_pipe.exists() and _clf_le.exists():
        state["clf_preprocessor"]  = joblib.load(_clf_pipe)
        state["clf_label_encoder"] = joblib.load(_clf_le)
        clf_models = {}
        for name in ["random_forest", "gradient_boosting", "logistic_regression", "mlp"]:
            p = ROOT / "models" / f"{name}_classification.pkl"
            if p.exists():
                clf_models[name] = joblib.load(p)
        state["clf_models"] = clf_models
    else:
        state["clf_models"] = {}

    # Classification metrics CSV
    _clf_csv = ROOT / "models" / "metrics_classification.csv"
    if _clf_csv.exists():
        df_clf = pd.read_csv(_clf_csv)
        # Normalise column order
        cols = [c for c in ["Model", "Accuracy", "F1-macro", "ROC-AUC"] if c in df_clf.columns]
        df_clf = df_clf[cols]
        state["clf_metrics"] = df_clf.to_dict("records")
    else:
        state["clf_metrics"] = []

    # Validation vs Test metrics CSV (generated by src/evaluate.py)
    _vt_csv = ROOT / "models" / "metrics_val_test.csv"
    if _vt_csv.exists():
        state["val_test_metrics"] = pd.read_csv(_vt_csv).to_dict("records")
    else:
        state["val_test_metrics"] = []

    # Pre-compute expensive caches
    _build_metrics_cache()
    _build_feature_importance_cache()

    yield
    state.clear()


def _build_metrics_cache():
    X_test = state["splits"]["X_test"]
    y_test = state["splits"]["y_test"]
    cv     = state["cv"]
    rows   = []
    for name, pipeline in state["models"].items():
        y_pred = pipeline.predict(X_test)
        rows.append({
            "name":        name,
            "label":       name.replace("_", " ").title(),
            "r2":          round(float(r2_score(y_test, y_pred)), 4),
            "rmse":        round(float(np.sqrt(mean_squared_error(y_test, y_pred))), 4),
            "mae":         round(float(mean_absolute_error(y_test, y_pred)), 4),
            "cv_r2_mean":  cv.get(name, {}).get("mean", 0),
            "cv_r2_std":   cv.get(name, {}).get("std",  0),
        })
    state["metrics"] = sorted(rows, key=lambda x: x["r2"], reverse=True)


def _build_feature_importance_cache():
    preferred = ["gradient_boosting", "random_forest"]
    target    = next((n for n in preferred if n in state["models"]), None)
    if target is None:
        state["feature_importance"] = {}
        return
    pipeline    = state["models"][target]
    feat_names  = get_feature_names(pipeline.named_steps["preprocessor"])
    importances = pipeline.named_steps["model"].feature_importances_
    state["feature_importance"] = {
        "model": target,
        "features": sorted(
            [{"feature": fn, "importance": round(float(imp), 4)}
             for fn, imp in zip(feat_names, importances)],
            key=lambda x: x["importance"], reverse=True,
        ),
    }


